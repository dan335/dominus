#!/usr/bin/env node
// Builds lib/client/bootstrap/bootstrap-settings.generated.css and .js, the way the
// huttonr:bootstrap3 build plugin did on every build until Meteor 3 (its
// assets package calls Assets.getText, which Meteor 3 removed). It reads
// lib/client/bootstrap/bootstrap-settings.json and bootstrap-variables.less
// as the plugin did, so run it again after changing either:
//
//   mkdir /tmp/bs && cd /tmp/bs && npm install --no-save less@2.6.0 bootstrap@3.3.6
//   NODE_PATH=/tmp/bs/node_modules node packages/bootstrap/build-static.js /tmp/bs/node_modules/bootstrap
//
// The first argument is a folder with Bootstrap 3.3.6's less/ and js/ (npm's
// bootstrap package, or huttonr:bootstrap3-assets' assets/bootstrap).
//
// The names sort where the plugin's output did, after bootstrap-mixins.less and
// before bootstrap-variables.less: the less package compiles that file on its
// own too, and its rules (p's margin and the like) must come after Bootstrap's.
const fs = require('fs');
const path = require('path');
const less = require('less');

const root = path.join(__dirname, '..', '..');
const settingsDir = path.join(root, 'lib', 'client', 'bootstrap');
const source = process.argv[2];
if (!source) throw new Error('usage: build-static.js <folder with bootstrap less/ and js/>');
const lessPath = path.join(source, 'less');
const jsPath = path.join(source, 'js');
const fontsUrl = '/packages/huttonr_bootstrap3-assets/assets/bootstrap/fonts/';

const settings = JSON.parse(fs.readFileSync(path.join(settingsDir, 'bootstrap-settings.json'), 'utf8'));
const read = function(file) { return fs.readFileSync(file, 'utf8'); };

// --- less: the modules in bootstrap.less's order, the ones the settings turn on
let modules = [];
const re = /@import\s+["'](.+)\.less["']/g;
const bootstrapLess = read(path.join(lessPath, 'bootstrap.less'));
for (let found; (found = re.exec(bootstrapLess));) if (found[1]) modules.push(found[1]);
modules.splice(modules.indexOf('variables'), 1);
modules.splice(modules.indexOf('mixins'), 1);
modules = modules.filter(function(name) { return settings.less.modules[name]; });
modules.splice(0, 0, 'variables', 'mixins');
if (settings.less.customVariables) modules.splice(modules.indexOf('variables') + 1, 0, 'bootstrap-variables');

// explode the imports, from bootstrap's less first and then the settings folder
const resolveImports = function(src, currentPath) {
  currentPath = currentPath || '.';
  return src.replace(/(?:\n|^|\*\/|;)\s*@import\s+["'](.+)["']\s*;\s*?/g, function(match, fn) {
    const fromBootstrap = path.join(lessPath, currentPath, fn);
    const res = fs.existsSync(fromBootstrap) ? read(fromBootstrap) : read(path.join(settingsDir, fn));
    return resolveImports(res, path.join(currentPath, path.dirname(fn)));
  });
};
const lessSrc = resolveImports(modules.map(function(name) { return '@import "' + name + '.less";'; }).join('\n'))
  .replace(/((?:\n|^|\*\/|;)\s*@icon-font-path\s*:\s*)(?:.+)/g, '$1"' + fontsUrl + '";')
  .replace(/((?:\n|^|\*\/|;)\s*@icon-font-name\s*:\s*)(?:.+)/g, '$1"glyphicons-halflings-regular";')
  .replace(/((?:\n|^|\*\/|;)\s*@icon-font-svg-id\s*:\s*)(?:.+)/g, '$1"glyphicons_halflingsregular";');

const header = '/* Generated by packages/bootstrap/build-static.js from Bootstrap 3.3.6 and\n' +
  '   lib/client/bootstrap/bootstrap-settings.json. Do not edit; run the script. */\n';

less.render(lessSrc, {}, function(error, output) {
  if (error) throw error;
  fs.writeFileSync(path.join(settingsDir, 'bootstrap-settings.generated.css'), header + output.css);

  // --- js: the modules the settings turn on, tooltip first (popover needs it)
  let jsModules = fs.readdirSync(jsPath).filter(function(f) { return /\.js$/.test(f); }).sort()
    .filter(function(f) { return settings.javascript.modules[f.replace(/\.js$/, '')]; });
  const tooltip = jsModules.indexOf('tooltip.js');
  if (tooltip > -1) jsModules.unshift(jsModules.splice(tooltip, 1)[0]);
  let src = '';
  for (const f of jsModules) src += read(path.join(jsPath, f)) + '\n';
  src = 'if (Meteor.isClient) { \n  ' + src.replace(/\n/g, '\n  ') + ' \n}\n';
  fs.writeFileSync(path.join(settingsDir, 'bootstrap-settings.generated.js'), header.replace(/^\/\*/, '//').replace(/\n   /, '\n//').replace(/ \*\/\n$/, '\n') + src);
  console.log('wrote bootstrap-settings.generated.css (' + output.css.length + ' bytes) and bootstrap-settings.generated.js (' + jsModules.join(', ') + ')');
});
